"""Deterministic source sealer using tracked Git files, never generated caches.

Run only after a clean git commit with a final source manifest; this is a
reproducibility aid, not a substitute for independently testing the sealed ZIP.
"""
from __future__ import annotations

import os
import re
from pathlib import Path
import subprocess
import sys
import zipfile


def tracked_files(root: Path) -> list[str]:
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=root)
    return sorted(s.decode("utf-8") for s in out.split(b"\0") if s)


def safe_archive_root(folder: str) -> bool:
    """Keep all ZIP members beneath one portable, explicit source root.

    A caller-supplied root such as "../outside" used to create ZIP members
    containing path traversal components, even with Git-tracked source files.
    """
    return (isinstance(folder, str) and
            re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", folder) is not None)


def seal(root: Path, destination: Path, folder: str) -> None:
    if not safe_archive_root(folder):
        raise ValueError("unsafe source ZIP root: expected one portable directory name")
    if subprocess.check_output(["git", "status", "--porcelain"], cwd=root).strip():
        raise ValueError("working tree is not clean; commit source before sealing")
    files = tracked_files(root)
    if any("__pycache__" in Path(f).parts or f.endswith(".pyc") for f in files):
        raise ValueError("source index includes generated bytecode")
    destination.parent.mkdir(parents=True, exist_ok=True)
    # ZIP timestamps and permissions fixed across hosts; 1980 is the ZIP epoch.
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in files:
            f = root / name
            if not f.is_file() or f.is_symlink():
                raise ValueError(f"invalid source file: {name}")
            info = zipfile.ZipInfo(folder + "/" + name, (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            z.writestr(info, f.read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: seal_release_source.py DEST_ZIP FOLDER_NAME")
    seal(Path(__file__).resolve().parents[1], Path(sys.argv[1]).resolve(), sys.argv[2])
